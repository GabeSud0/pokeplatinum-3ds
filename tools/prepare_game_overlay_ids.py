#!/usr/bin/env python3
"""Write the overlay ID symbols the DS linker made, as a GNU ld script.

Usage:
    python tools/prepare_game_overlay_ids.py --lsf build/upstream/platinum.us/main.lsf \
        --output build/game-link/overlay_ids.ld

The game names overlays with FS_OVERLAY_ID(name), which NitroSDK defines as
the address of the symbol SDK_OVERLAY_<name>_ID. Nintendo's linker defined
one such symbol per "Overlay <name>" entry in the linker spec (main.lsf),
at an address equal to the overlay's number: its position in that list,
from 0 (overlay5 is the 6th entry, so 5). This writes the same symbols as
absolute ld assignments; pass the file to the linker with the game's objects.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

OVERLAY = re.compile(r"^Overlay\s+([A-Za-z_][A-Za-z0-9_]*)\s*$", re.M)


def overlay_names(lsf_text: str) -> list[str]:
    names = OVERLAY.findall(lsf_text)
    if not names:
        raise ValueError("no Overlay entries in the linker spec")
    if len(set(names)) != len(names):
        raise ValueError("an overlay name appears twice")
    return names


def render(names: list[str]) -> str:
    lines = [
        "/* Generated by tools/prepare_game_overlay_ids.py from main.lsf. */",
        "/* SDK_OVERLAY_<name>_ID is at the overlay's number, as the DS linker made it. */",
    ]
    lines += [f"SDK_OVERLAY_{name}_ID = {index};" for index, name in enumerate(names)]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--lsf", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    text = render(overlay_names(args.lsf.read_text(encoding="utf-8")))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if not args.output.is_file() or args.output.read_text(encoding="utf-8") != text:
        args.output.write_text(text, encoding="utf-8")
    print(f"Wrote {len(re.findall(r'^SDK_OVERLAY_', text, re.M))} overlay IDs to {args.output}")


if __name__ == "__main__":
    main()
