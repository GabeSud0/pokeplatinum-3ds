#!/usr/bin/env python3
"""Write the overlay IDs the DS linker made: a C header, and a GNU ld script.

Usage:
    python tools/prepare_game_overlay_ids.py --lsf build/upstream/platinum.us/main.lsf \
        --output build/game-link/overlay_ids.ld --header build/game-link/overlay_ids.h

The game names overlays with FS_OVERLAY_ID(name). An overlay's ID is its
position in the linker spec's list of "Overlay <name>" entries (main.lsf),
from 0 (overlay5 is the 6th entry, so 5).

In NitroSDK, FS_OVERLAY_ID(name) is the address of the symbol
SDK_OVERLAY_<name>_ID, which Nintendo's linker placed at that number. The
port's NitroSDK (patches/NitroSDK) uses a constant instead,
SDK_PORT_OVERLAY_ID_<name>, from the header this writes: an address doesn't
fit the game's 32-bit overlay-ID fields on a 64-bit PC, a constant does on
every machine. The game is compiled with the header (-include). The ld
script defines the symbols too, as Nintendo's linker did, for any code that
still refers to them.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

OVERLAY = re.compile(r"^Overlay\s+([A-Za-z_][A-Za-z0-9_]*)\s*$", re.M)


def overlay_names(lsf_text: str) -> list[str]:
    names = OVERLAY.findall(lsf_text)
    if not names:
        raise ValueError("no Overlay entries in the linker spec")
    if len(set(names)) != len(names):
        raise ValueError("an overlay name appears twice")
    return names


def render(names: list[str]) -> str:
    lines = [
        "/* Generated by tools/prepare_game_overlay_ids.py from main.lsf. */",
        "/* SDK_OVERLAY_<name>_ID is at the overlay's number, as the DS linker made it. */",
    ]
    lines += [f"SDK_OVERLAY_{name}_ID = {index};" for index, name in enumerate(names)]
    return "\n".join(lines) + "\n"


def render_header(names: list[str]) -> str:
    lines = [
        "/* Generated by tools/prepare_game_overlay_ids.py from main.lsf. */",
        "/* Each overlay's ID: its position in the linker spec. FS_OVERLAY_ID(name)",
        "   is SDK_PORT_OVERLAY_ID_<name> in the port's NitroSDK. */",
        "#ifndef PORT_GAME_OVERLAY_IDS_H",
        "#define PORT_GAME_OVERLAY_IDS_H",
        "",
        "enum {",
    ]
    lines += [f"    SDK_PORT_OVERLAY_ID_{name} = {index}," for index, name in enumerate(names)]
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.is_file() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--lsf", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--header", type=Path)
    args = parser.parse_args()
    names = overlay_names(args.lsf.read_text(encoding="utf-8"))
    write(args.output, render(names))
    if args.header:
        write(args.header, render_header(names))
    print(f"Wrote {len(names)} overlay IDs to {args.output}" +
          (f" and {args.header}" if args.header else ""))


if __name__ == "__main__":
    main()
