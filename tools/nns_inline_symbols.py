#!/usr/bin/env python3
"""Write a C file that includes every NitroSystem header.

Usage:
    python tools/nns_inline_symbols.py OUTPUT.c

Why: NitroSystem's headers define many small functions with NNS_INLINE
(through NNS_G2D_INLINE, NNS_G3D_INLINE, ...), which is plain `inline`.
Metrowerks kept one copy of each when linking. GCC instead exports a full
copy from every file that includes the header, so two such files can't be
linked together ("multiple definition").

The port's build (3ds_port/nitrosystem/Makefile) compiles this file with the
same flags as everything else; the functions it exports are exactly the ones
every includer gets. Their names go into a list, and after compiling each
object file the build marks them as weak symbols (objcopy
--weaken-symbols). The linker then keeps one copy, as Metrowerks did. The
copies are identical, since they come from the same header.

Covers the public headers (include/nnsys) and NitroSystem's private ones
(libraries/*/include). Leaves out mcs (the link to Nintendo's PC debugging
tools, which needs their SDK) and the Windows-only headers.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NNS = ROOT / "build" / "NitroSystem"


def headers() -> list[Path]:
    found = list((NNS / "include" / "nnsys").rglob("*.h"))
    found += list((NNS / "libraries").glob("*/include/**/*.h"))
    return sorted(p for p in found
                  if "mcs" not in p.relative_to(NNS).parts
                  and p.name not in ("mcs.h",) and "win32" not in p.name)


def main() -> int:
    if len(sys.argv) != 2:
        print("usage: python tools/nns_inline_symbols.py OUTPUT.c")
        return 2
    if not (NNS / "include").is_dir():
        print("build/NitroSystem not found. Run: python tools/bootstrap.py")
        return 1
    lines = ["/* Generated by tools/nns_inline_symbols.py: every NitroSystem header. */",
             "#include <nitro.h>"]
    out = Path(sys.argv[1])
    # Paths relative to the generated file (the compiler looks for a quoted
    # include next to the file first): an absolute path from MSYS2 on Windows
    # (/home/...) means nothing to devkitPro's compiler, a Windows program.
    base = out.resolve().parent
    lines += [f'#include "{Path(os.path.relpath(p, base)).as_posix()}"' for p in headers()]
    text = "\n".join(lines) + "\n"
    out.parent.mkdir(parents=True, exist_ok=True)
    # Only rewrite when it changes, so nothing is rebuilt for no reason; but
    # mark it up to date, or make would run this again on every build (the
    # headers it lists are newer after each bootstrap).
    if not out.is_file() or out.read_text() != text:
        out.write_text(text)
    else:
        os.utime(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
