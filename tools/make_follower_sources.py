#!/usr/bin/env python3
"""Pin the follower Pokémon's sprites the builder fetches: writes
builder/follower_sources.py from a checkout of pret/pokeheartgold.

    python3 tools/make_follower_sources.py PATH/TO/pokeheartgold

The follower sprites are HeartGold and SoulSilver's (Nintendo, Game Freak
and Creatures' work): never in this repository or its releases. The
builder downloads them on the player's computer from pokeheartgold at the
commit pinned here, checks each file's size and SHA-256, and puts them in
the player's data pack (builder/followers.py, docs/PAK_FORMAT.md).

What this writes is only numbers: the commit, each file's size and SHA-256,
and three tables from pokeheartgold's src/follow_mon.c (by species: the
first sprite, the number of forms after it, whether females have their own
sprite), used the way FollowMon_GetSpriteID uses them. Run it again with a
newer checkout to re-pin (CI checks the tables' shape, not the files).
"""
from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "builder" / "follower_sources.py"

REPO = "pret/pokeheartgold"
SPRITE_DIR = "files/data/mmodel/mmodel"
FIRST_FILE = 297     # mmodel_00000297.NSBTX = SPRITE_FOLLOWER_MON_BULBASAUR
COUNT = 566          # ... to SPRITE_FOLLOWER_MON_ARCEUS_DARK (993 - 428 + 1)
SPECIES = 493        # the national dex in Platinum


def _table(source: str, name: str) -> list[str]:
    match = re.search(r"static const u16 " + name + r"\[\] = \{(.*?)\};", source, re.S)
    if match is None:
        sys.exit(f"follow_mon.c: no table {name}")
    body = re.sub(r"//[^\n]*", "", match.group(1))
    return [v.strip() for v in body.split(",") if v.strip()]


def read_tables(checkout: Path) -> tuple[list[int], list[int], list[int]]:
    source = (checkout / "src" / "follow_mon.c").read_text(encoding="utf-8")
    idx = {}
    for line in (checkout / "include" / "constants" / "follow_mon_idx.h").read_text(encoding="utf-8").splitlines():
        m = re.match(r"#define\s+(FOLLOWER_MON_\w+)\s+(\d+)", line)
        if m:
            idx[m.group(1)] = int(m.group(2))
    model = [idx[v] if v in idx else int(v, 0) for v in _table(source, "sModelIndexLUT")]
    forms = [int(v, 0) for v in _table(source, "sFormMaxLUT")]
    female = [1 if v == "TRUE" else 0 if v == "FALSE" else int(v, 0) for v in _table(source, "sFemaleFlagLUT")]
    # sModelIndexLUT starts with species 0 (none); the others with species 1.
    model = model[1:SPECIES + 1]
    forms = forms[:SPECIES]
    female = female[:SPECIES]
    if not (len(model) == len(forms) == len(female) == SPECIES):
        sys.exit(f"follow_mon.c: tables of {len(model)}, {len(forms)}, {len(female)} species, not {SPECIES}")
    for s in range(SPECIES):
        last = model[s] + (1 if female[s] else forms[s])
        if not 0 <= model[s] or last >= COUNT:
            sys.exit(f"follow_mon.c: species {s + 1} sprite {model[s]}+ outside the {COUNT} files")
    return model, forms, female


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("checkout", type=Path, help="a pret/pokeheartgold checkout (its files/data/mmodel and src)")
    args = parser.parse_args()
    commit = subprocess.run(["git", "-C", str(args.checkout), "rev-parse", "HEAD"], check=True,
                            capture_output=True, text=True).stdout.strip()
    model, forms, female = read_tables(args.checkout)
    files = []
    for n in range(COUNT):
        data = (args.checkout / SPRITE_DIR / f"mmodel_{FIRST_FILE + n:08d}.NSBTX").read_bytes()
        files.append((len(data), hashlib.sha256(data).hexdigest()))

    def rows(values, per=24):
        return "\n".join("    " + ", ".join(str(v) for v in values[i:i + per]) + "," for i in range(0, len(values), per))

    text = f'''"""Generated by tools/make_follower_sources.py: don't edit by hand.

The follower Pokémon's sprites the builder fetches (builder/followers.py):
HeartGold and SoulSilver's, from {REPO} at the commit below, never in this
repository or its releases. Only numbers here: each file's size and
SHA-256, and by species (1-{SPECIES}) the first sprite, the forms after it
and whether females have their own (src/follow_mon.c's tables)."""

REPO = "{REPO}"
COMMIT = "{commit}"
SPRITE_PATH = "{SPRITE_DIR}/mmodel_{{:08d}}.NSBTX"
FIRST_FILE = {FIRST_FILE}

# (size, SHA-256) of sprite n = file FIRST_FILE + n
FILES = [
''' + "\n".join(f'    ({size}, "{digest}"),' for size, digest in files) + f'''
]

# by species - 1
MODEL = [
{rows(model)}
]
FORM_MAX = [
{rows(forms, 40)}
]
FEMALE = [
{rows(female, 40)}
]
'''
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.relative_to(ROOT)}: {COUNT} sprites at {REPO}@{commit[:12]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
